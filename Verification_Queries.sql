SELECT 'DEPARTMENT' AS TABLE_NAME, COUNT(*) AS TOTAL
FROM DEPARTMENT
UNION ALL
SELECT 'STUDENT', COUNT(*) FROM STUDENT
UNION ALL
SELECT 'FACULTY', COUNT(*) FROM FACULTY
UNION ALL
SELECT 'COURSE', COUNT(*) FROM COURSE
UNION ALL
SELECT 'STUDENT_EMAIL', COUNT(*) FROM STUDENT_EMAIL
UNION ALL
SELECT 'STUDENT_PHONE', COUNT(*) FROM STUDENT_PHONE
UNION ALL
SELECT 'FACULTY_EMAIL', COUNT(*) FROM FACULTY_EMAIL
UNION ALL
SELECT 'FACULTY_PHONE', COUNT(*) FROM FACULTY_PHONE
UNION ALL
SELECT 'ENROLLMENT', COUNT(*) FROM ENROLLMENT;


SELECT
    S.Student_ID,
    S.First_Name,
    D.Dept_Name,
    C.Course_Name,
    F.First_Name AS Faculty_Name,
    E.Enrollment_Date,
    E.Grade
FROM ENROLLMENT E
JOIN STUDENT S
    ON E.Student_ID = S.Student_ID
JOIN DEPARTMENT D
    ON S.Dept_ID = D.Dept_ID
JOIN COURSE C
    ON E.Course_ID = C.Course_ID
JOIN FACULTY F
    ON E.Faculty_ID = F.Faculty_ID;